#!/usr/bin/env python3
"""Sync plugin versions from the Codex manifest, or check them without writes.

Only the named plugin version fields are managed. Validator evidence must be
regenerated by its validators; marketplace metadata versions are independent.
Exit codes: 0 consistent/synced, 1 drift in --check, 2 invalid input or I/O error.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from release_payload import SEMVER_PATTERN


PLUGIN = "kaoyan-408"
SOURCE = "plugins/kaoyan-408/.codex-plugin/plugin.json"
MANIFESTS = (
    "plugins/kaoyan-408/.zcode-plugin/plugin.json",
    "plugins/kaoyan-408/.codebuddy-plugin/plugin.json",
    ".cursor-plugin/plugin.json",
    "plugins/kaoyan-408/.claude-plugin/plugin.json",
)
MARKETPLACES = (
    ".claude-plugin/marketplace.json",
    ".codebuddy-plugin/marketplace.json",
)
SEMVER = re.compile(
    r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)"
    r"(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?"
    r"(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?"
)


class VersionError(ValueError):
    """A manifest, version, or filesystem boundary is invalid."""


@dataclass(frozen=True)
class Change:
    relative: str
    before: bytes
    after: bytes
    previous_version: str


def reject_links(path: Path) -> None:
    for part in (path, *path.parents):
        if part.is_symlink() or (hasattr(part, "is_junction") and part.is_junction()):
            raise VersionError(f"symlink or junction is not allowed: {part}")


def inside(root: Path, relative: str) -> Path:
    path = root / relative
    reject_links(path)
    if not path.resolve().is_relative_to(root):
        raise VersionError(f"path escapes repository: {relative}")
    return path


def unique_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise VersionError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def reject_constant(value: str) -> None:
    raise VersionError(f"nonstandard JSON constant: {value}")


def read_document(path: Path) -> tuple[dict, bytes]:
    raw = path.read_bytes()
    try:
        document = json.loads(
            raw.decode("utf-8"), object_pairs_hook=unique_object,
            parse_constant=reject_constant,
        )
    except (UnicodeError, ValueError) as exc:
        raise VersionError(f"invalid JSON in {path}: {exc}") from exc
    if not isinstance(document, dict):
        raise VersionError(f"JSON object required: {path}")
    return document, raw


def require_version(value: object, label: str) -> str:
    match = SEMVER.fullmatch(value) if isinstance(value, str) else None
    if match is None:
        raise VersionError(f"invalid semantic version in {label}: {value!r}")
    if re.fullmatch(SEMVER_PATTERN, value) is None:
        raise VersionError(f"version is not supported by repository release policy: {label}")
    prerelease = match.group(1)
    if prerelease and any(part.isdigit() and len(part) > 1 and part.startswith("0") for part in prerelease.split(".")):
        raise VersionError(f"numeric prerelease identifier has a leading zero in {label}")
    return value


def prepare(root: Path) -> tuple[str, list[Change]]:
    source, _ = read_document(inside(root, SOURCE))
    if source.get("name") != PLUGIN:
        raise VersionError(f"source manifest name must be {PLUGIN}")
    version = require_version(source.get("version"), SOURCE)
    targets = [(name, False) for name in MANIFESTS]
    targets.extend((name, True) for name in MARKETPLACES)
    changes = []
    for relative, marketplace in targets:
        document, raw = read_document(inside(root, relative))
        entry = document
        if marketplace:
            entries = document.get("plugins")
            if not isinstance(entries, list) or any(not isinstance(item, dict) for item in entries):
                raise VersionError(f"plugins must be an array of objects: {relative}")
            matches = [item for item in entries if item.get("name") == PLUGIN]
            if len(matches) != 1:
                raise VersionError(f"exactly one {PLUGIN} entry required: {relative}")
            entry = matches[0]
        elif document.get("name") != PLUGIN:
            raise VersionError(f"manifest name must be {PLUGIN}: {relative}")
        previous = require_version(entry.get("version"), relative)
        if previous != version:
            entry["version"] = version
            updated = (json.dumps(document, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode("utf-8")
            changes.append(Change(relative, raw, updated, previous))
    return version, changes


def backup_location(root: Path, requested: Path | None) -> Path:
    if requested is None:
        parent = Path(tempfile.gettempdir()).resolve()
        reject_links(parent)
        if parent.is_relative_to(root):
            raise VersionError("temporary backup directory must be outside repository")
        return Path(tempfile.mkdtemp(prefix="kaoyan-408-version-backup-", dir=parent))
    backup = Path(os.path.abspath(requested.expanduser()))
    reject_links(backup)
    if backup.resolve().is_relative_to(root):
        raise VersionError("backup directory must be outside repository")
    if backup.exists():
        raise VersionError(f"backup directory already exists: {backup}")
    backup.mkdir()
    return backup


def write_changes(root: Path, changes: list[Change], requested: Path | None) -> Path:
    # Parse/validate the complete input set before creating any backup or output.
    # Save every original before replacing any target. Backups remain on failure.
    backup = backup_location(root, requested)
    staged: list[tuple[Path, Path, bytes]] = []
    try:
        for change in changes:
            target = inside(root, change.relative)
            if target.read_bytes() != change.before:
                raise VersionError(f"file changed during preparation: {change.relative}")
            saved = backup / change.relative
            saved.parent.mkdir(parents=True, exist_ok=True)
            saved.write_bytes(change.before)
            with tempfile.NamedTemporaryFile(prefix=".version-sync-", dir=target.parent, delete=False) as stream:
                temporary = Path(stream.name)
                staged.append((temporary, target, change.before))
                stream.write(change.after)
            temporary.chmod(target.stat().st_mode)
        # Recheck the full set before the first replacement.
        for _, target, before in staged:
            reject_links(target)
            if target.read_bytes() != before:
                raise VersionError(f"file changed during preparation: {target}")
        for temporary, target, _ in staged:
            os.replace(temporary, target)
    except (OSError, ValueError) as exc:
        raise VersionError(f"write failed; original files saved in {backup}: {exc}") from exc
    finally:
        for temporary, _, _ in staged:
            if temporary.exists():
                temporary.unlink()
    return backup


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="read-only check; exit 1 on version drift")
    mode.add_argument("--write", action="store_true", help="sync managed version fields after external backup")
    parser.add_argument("--backup-dir", type=Path, help="new directory outside repo; default: unique temporary directory")
    args = parser.parse_args(argv)
    try:
        root = Path(os.path.abspath(args.repo.expanduser()))
        reject_links(root)
        root = root.resolve(strict=True)
        if not root.is_dir():
            raise VersionError(f"repository directory required: {root}")
        version, changes = prepare(root)
        for change in changes:
            print(f"DRIFT {change.relative}: {change.previous_version} -> {version}")
        if args.check:
            if not changes:
                print(f"OK plugin versions match {version}")
            return 1 if changes else 0
        if changes:
            backup = write_changes(root, changes, args.backup_dir)
            print(f"SYNCED {len(changes)} files to {version}; backup: {backup}")
        else:
            print(f"OK plugin versions match {version}; no files changed")
        return 0
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
